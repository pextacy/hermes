// Writes the compiled ABIs into abi.ts so TypeScript packages import them without Foundry.
import { readFileSync, writeFileSync } from 'node:fs';
const read = (n: string) => JSON.parse(readFileSync(new URL(`../out/${n}.sol/${n}.json`, import.meta.url), 'utf8'));
const htlc = read('HermesHTLC');
const usdc = read('MockUSDC');
const out = `// Generated by scripts/export-abi.ts from forge build output. Do not edit.
export const hermesHtlcAbi = ${JSON.stringify(htlc.abi, null, 2)} as const;
export const hermesHtlcBytecode = ${JSON.stringify(htlc.bytecode.object)} as const;
export const mockUsdcAbi = ${JSON.stringify(usdc.abi, null, 2)} as const;
export const mockUsdcBytecode = ${JSON.stringify(usdc.bytecode.object)} as const;
`;
writeFileSync(new URL('../abi.ts', import.meta.url), out);
console.log('abi.ts written');
